# -*- coding: utf-8 -*-
"""给 v4/index.html 追加 v4.11.66 更新日志（锚点 = v4.11.65 条目结尾）。
含反引号/转义，故写成 .py 文件执行，不走 shell 双引号（铁律 3）。"""
import sys
sys.stdout.reconfigure(encoding='utf-8', errors='replace')

P = 'v4/index.html'
s = open(P, encoding='utf-8', newline='').read()

ANT = '两者叠加才会出现「修了还是空」。</div>'
if s.count(ANT) != 1:
    print('!! 锚点出现 %d 次，中止' % s.count(ANT))
    sys.exit(1)

NEW = (
    '两者叠加才会出现「修了还是空」。<br>'
    '<b>v4.11.66（2026-11-10）把「会悄悄变少/变慢」的三件事提到页面顶部预警</b>：'
    '起因是三处结构体检实测 —— ① 接口单次上限 1200 行，触顶后按现有逻辑<b>保留最新 1200 条、丢弃最早的</b>，'
    '而原来只在状态栏角落写 4 个字「（已达上限）」，12px 小字还排在表格名后面，等于没有提示；'
    '② 日报表实测 443 行、<b>11.97 行/日</b>（2026-10-03~11-08 现测，非外推）⇒ 约 63 天触顶，'
    '按现有增长到 2027-01-12 前后；③ 该表 41 个字段里 <b>7 个是公式列</b>，飞书按<b>全表重算</b>，'
    '实测「取 50 行要 34.8 秒、取 443 行只要 20.5 秒」—— 耗时由表里有多少行决定，不由取多少行决定，'
    '所以 90 秒超时是硬墙，撞上就回退旧数据。处置：新增页面顶部预警条（<code>#fsBanner</code>），三档 —— '
    '红色「云端取不到数，当前为上次成功同步/本地快照」、'
    '橙色「已截断：只加载了最新 N 条（表内共 M 条），更早的数据本次未加载」、'
    '橙色「行数预警：当前 N 行，已用掉单次上限的 X%，按实测增长速度约 D 天后触顶」。'
    '增长率从本次数据的日期跨度<b>现算</b>，不写死数字；达上限 85% 即预警。'
    '同时把 <code>limited</code> / <code>total_all</code> 留在前端状态里（原来这两个值只用于拼一句文案、用完即弃）。'
    '</div>'
)

s2 = s.replace(ANT, NEW)
open(P, 'w', encoding='utf-8', newline='').write(s2)
print('追加完成；4.11.66 出现', s2.count('4.11.66'), '次；4.11.65 出现', s2.count('4.11.65'), '次')
